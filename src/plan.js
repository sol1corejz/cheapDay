export function plural(n, one, few, many) {
  const n10 = n % 10;
  const n100 = n % 100;
  if (n10 === 1 && n100 !== 11) return one;
  if (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) return few;
  return many;
}

export function money(n) {
  return `${new Intl.NumberFormat("ru-RU").format(n)}\u00a0₽`;
}

export function todayISO() {
  const d = new Date();
  const z = (n) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${z(d.getMonth() + 1)}-${z(d.getDate())}`;
}

function parseISO(iso) {
  const [y, m, d] = iso.split("-").map(Number);
  return new Date(y, m - 1, d);
}

export function addDays(iso, n) {
  const date = parseISO(iso);
  date.setDate(date.getDate() + n);
  return date;
}

function monthName(date) {
  const parts = new Intl.DateTimeFormat("ru-RU", { day: "numeric", month: "long" }).formatToParts(date);
  return parts.find((part) => part.type === "month").value;
}

export function formatRange(start, count) {
  const a = addDays(start, 0);
  const b = addDays(start, count - 1);
  if (a.getMonth() === b.getMonth() && a.getFullYear() === b.getFullYear()) {
    return `${a.getDate()}–${b.getDate()} ${monthName(b)}`;
  }
  return `${a.getDate()} ${monthName(a)} – ${b.getDate()} ${monthName(b)}`;
}

export function formatDate(date) {
  const weekday = new Intl.DateTimeFormat("ru-RU", { weekday: "long" }).format(date);
  return {
    kicker: weekday,
    title: `${date.getDate()} ${monthName(date)}`,
  };
}

export function isSameDay(a, b) {
  return a.getFullYear() === b.getFullYear() && a.getMonth() === b.getMonth() && a.getDate() === b.getDate();
}

export function parseMoney(value) {
  const n = Number(String(value).replace(/\s/g, "").replace(",", "."));
  if (!Number.isFinite(n)) return null;
  return Math.round(n);
}

export function describeDraft(budget, days) {
  const total = parseMoney(budget);
  if (!total || total < 1) return { big: "Введите сумму", sub: "И число дней — с сегодняшнего." };
  const share = total / days;
  const big = Number.isInteger(share) ? `по ${money(share)}` : `около ${money(Math.round(share))}`;
  return {
    big,
    sub: `${formatRange(todayISO(), days)} · ${days} ${plural(days, "день", "дня", "дней")}, до покупок`,
  };
}

function sumPrices(ids) {
  return ids.reduce((sum, id) => sum + ITEMS[id].price, 0);
}

function fitList(ids, allowance, usedStock) {
  const chosen = [];
  const used = new Set();
  let left = allowance;
  ids.forEach((id) => {
    if (used.has(id) || !ITEMS[id]) return;
    if (ITEMS[id].stock && usedStock.has(id)) return;
    if (ITEMS[id].price > left) return;
    chosen.push(id);
    used.add(id);
    left -= ITEMS[id].price;
  });
  return chosen;
}

function topUp(ids, allowance, usedStock, salt) {
  const chosen = ids.slice();
  const used = new Set(chosen);
  let left = allowance - sumPrices(chosen);
  const limit = left > 400 ? 6 : 2;
  for (let n = 0; n < limit && left >= 18; n += 1) {
    const preferStock = left > 220;
    const fits = (id) => !used.has(id) && ITEMS[id].price <= left && !(ITEMS[id].stock && usedStock.has(id));
    let avail = TOPUP.filter((id) => fits(id) && (!preferStock || ITEMS[id].stock));
    if (!avail.length) avail = TOPUP.filter(fits);
    if (!avail.length) break;
    const closest = Math.min(...avail.map((id) => left - ITEMS[id].price));
    const band = avail.filter((id) => left - ITEMS[id].price <= closest + 24);
    const id = band[Math.abs(salt + n) % band.length];
    chosen.push(id);
    used.add(id);
    left -= ITEMS[id].price;
  }
  return chosen;
}

function composeDay(allowance, salt, usedStock) {
  const variants = TEMPLATES.map((ids) => fitList(ids, allowance, usedStock));
  const max = Math.max(...variants.map((ids) => sumPrices(ids)));
  const band = variants.filter((ids) => sumPrices(ids) >= max - Math.max(36, Math.round(max * 0.08)));
  let chosen = band[Math.abs(salt) % band.length].slice();
  if (allowance - sumPrices(chosen) >= 18) chosen = topUp(chosen, allowance, usedStock, salt);
  return chosen;
}

function trimTo(ids, allowance) {
  const next = ids.filter((id) => ITEMS[id]);
  while (next.length && sumPrices(next) > allowance) next.pop();
  return next;
}

export function freshDays(count) {
  return Array.from({ length: count }, () => ({ seed: 0, locked: false, items: [] }));
}

export function buildPlan(model) {
  let left = model.total;
  const equal = model.total / model.dayCount;
  const usedStock = new Set();
  const days = [];
  let incoming = false;

  for (let i = 0; i < model.dayCount; i += 1) {
    const prev = model.days[i];
    const allowance = Math.ceil(left / (model.dayCount - i));
    const items = prev.locked
      ? trimTo(prev.items, allowance)
      : composeDay(allowance, prev.seed * 13 + i, usedStock);
    items.forEach((id) => {
      if (ITEMS[id].stock) usedStock.add(id);
    });
    const spent = sumPrices(items);
    const carry = allowance - spent;
    const diff = allowance - equal;
    days.push({
      seed: prev.seed,
      locked: prev.locked,
      allowance,
      items,
      spent,
      carry,
      showPlus: incoming && diff >= 1,
      showMinus: incoming && diff <= -1,
      diff: Math.round(diff),
    });
    incoming = incoming || carry > 0;
    left -= spent;
  }

  return { ...model, days, leftover: left };
}

export function carryText(carry, isLast) {
  if (carry <= 0) return isLast ? "Бюджет сходится ровно" : "День сходится ровно";
  if (isLast) return `Остаток ${money(carry)} свободен`;
  return `Остаток ${money(carry)} уйдёт на следующие дни`;
}

export function applyTtl(data, now) {
  if (!data?.state?.expiresAt || now <= data.state.expiresAt) return data;
  return {
    ...data,
    state: {
      ...data.state,
      plan: null,
      budget: "7000",
      dayCount: 7,
      hint: true,
      expiresAt: null,
    },
  };
}
